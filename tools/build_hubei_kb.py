TEST_QUERIES = [
    "湖北有哪些必去的景点？",
    "黄鹤楼门票多少钱？",
    "武汉有什么好吃的？",
    "适合带孩子去的地方有哪些？",
    "想去避暑，推荐哪里？",
    "湖北省博物馆怎么预约、免费吗？",
    "武当山金顶要另外买票吗？",
]


def main():
    kb = TourismKB(CONFIG)
    print(f"[init] embedding={type(kb.embedding).__name__}  emb_type={kb._emb_type}")

    n = kb.ingest_structured("hubei", HUBEI_SEED)
    print(f"[ingest] hubei 新增 {n} 条，当前 {len(kb.list_docs('hubei'))} 条")

    print("\n===== 混合检索验证 =====")
    for q in TEST_QUERIES:
        top = kb.hybrid_retrieve("hubei", q, top_k=3)
        print(f"\n● 问：{q}")
        for d in top:
            print(f"   - [{d['_sim']:.3f}|kw{d['_kw']:.2f}] 《{d['title']}》({d['type']})")
        # 无 LLM 时的确定性答案（片段拼接）
        ans = kb.query("hubei", q, use_llm=False)["answer"]
        print(f"   拼接答案(前120字): {ans[:120]}...")

    print("\n===== query() 将发给 LLM 的上下文预览（首问） =====")
    top = kb.hybrid_retrieve("hubei", TEST_QUERIES[0], top_k=5)
    ctx = "\n\n".join(
        f"[{i+1}] 《{d['title']}》（{d['type']}）\n{d['text']}"
        for i, d in enumerate(top)
    )
    print(ctx[:900] + ("\n... (truncated)" if len(ctx) > 900 else ""))


if __name__ == "__main__":
    main()
